-- Пункты выдачи
CREATE TABLE ПунктыВыдачи (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Адрес NVARCHAR(200) NOT NULL
);

-- Категории товаров
CREATE TABLE КатегорииТоваров (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Название NVARCHAR(100) NOT NULL
);

-- Поставщики
CREATE TABLE Поставщики (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Название NVARCHAR(100) NOT NULL
);

-- Производители
CREATE TABLE Производители (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Название NVARCHAR(100) NOT NULL
);

-- Товары
CREATE TABLE Товары (
    Артикул NVARCHAR(20) PRIMARY KEY,
    НаименованиеТовара NVARCHAR(200) NOT NULL,
    ЕдиницаИзмерения NVARCHAR(20) NOT NULL DEFAULT 'шт.',
    Цена DECIMAL(10,2) NOT NULL,
    Поставщик NVARCHAR(100) NOT NULL,
    Производитель NVARCHAR(100) NOT NULL,
    КатегорияТовара NVARCHAR(100) NOT NULL,
    ДействующаяСкидка INT NOT NULL DEFAULT 0,
    КолвоНаСкладе INT NOT NULL DEFAULT 0,
    ОписаниеТовара NVARCHAR(500),
    Фото NVARCHAR(100)
);

-- Роли пользователей
CREATE TABLE Роли (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    Название NVARCHAR(50) NOT NULL
);

-- Пользователи
CREATE TABLE Пользователи (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    РольID INT NOT NULL REFERENCES Роли(ID),
    ФИО NVARCHAR(200) NOT NULL,
    Логин NVARCHAR(100) NOT NULL UNIQUE,
    Пароль NVARCHAR(100) NOT NULL
);

-- Заказы
CREATE TABLE Заказы (
    НомерЗаказа INT IDENTITY(1,1) PRIMARY KEY,
    ДатаЗаказа DATE NOT NULL,
    ДатаДоставки DATE NOT NULL,
    ПунктВыдачиID INT NOT NULL REFERENCES ПунктыВыдачи(ID),
    ФИОКлиента NVARCHAR(200) NOT NULL,
    КодДляПолучения INT NOT NULL,
    СтатусЗаказа NVARCHAR(50) NOT NULL DEFAULT 'Новый'
);

-- Состав заказа (позиции)
CREATE TABLE СоставЗаказа (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    НомерЗаказа INT NOT NULL REFERENCES Заказы(НомерЗаказа) ON DELETE CASCADE,
    АртикулТовара NVARCHAR(20) NOT NULL REFERENCES Товары(Артикул),
    Количество INT NOT NULL DEFAULT 1
);

GO

